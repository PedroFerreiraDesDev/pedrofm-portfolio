const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../app.js','utf8');
const start=source.indexOf("gallery.addEventListener('wheel',e=>{");
const end=source.indexOf("gallery.addEventListener('scroll'",start);
let handler,now=1000;const moves=[];
const c={arrivalWheel:null,mode:'gallery',trackBusy:false,wheelTotal:0,wheelStamp:0,lastMove:1000,Date:{now:()=>now},gallery:{clientHeight:800,addEventListener:(name,fn)=>handler=fn},move:d=>moves.push(d),navigate(){}};
vm.createContext(c);vm.runInContext(source.slice(start,end),c);
const wheel=(deltaY,other={})=>{now+=16;handler({deltaY,deltaX:0,deltaMode:0,preventDefault(){},...other});};
wheel(60);assert.deepEqual(moves,[1],'arrival must not wait 980 ms');
c.trackBusy=true;for(let i=0;i<80;i++)wheel(20);assert.equal(moves.length,1,'no queue during transition');
c.trackBusy=false;wheel(20);wheel(20);wheel(20);assert.deepEqual(moves,[1,1],'continuous gesture resumes after transition');
wheel(30);wheel(-30);wheel(-30);assert.deepEqual(moves,[1,1,-1],'direction change clears old total');
wheel(120,{ctrlKey:true});assert.equal(moves.length,3,'browser zoom preserved');
wheel(0,{deltaX:60});assert.equal(moves.length,4,'horizontal trackpad');
wheel(4,{deltaMode:1});assert.equal(moves.length,5,'line delta normalized');
c.arrivalWheel={at:now,delta:60,until:now+450};
wheel(40);wheel(30);assert.equal(moves.length,5,'tail must not skip first cover');
wheel(80);assert.equal(moves.length,6,'fresh impulse resumes immediately');
c.arrivalWheel={at:now,delta:40,until:now+450};now+=130;wheel(60);assert.equal(moves.length,7,'new gesture after gap');
c.arrivalWheel={at:now,delta:40,until:now+450};wheel(-60);assert.equal(moves.length,8,'reverse is immediate');
c.arrivalWheel={at:now,delta:40,until:now+450};for(let i=0;i<40;i++)wheel(10);assert.equal(c.arrivalWheel,null,'guard expires even with continuous input');
console.log('OK: continuous scroll, arrival inertia, fresh input, reverse, bounded guard.');
